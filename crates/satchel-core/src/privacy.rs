#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn excluded_apps_are_recognised_like_capture_does() {
        let s = Settings { excluded_app_ids: vec!["com.example.Vault".into(), "KeePass.exe".into()], ..Settings::default() };
        assert!(is_excluded_app("com.example.vault", &s));
        assert!(is_excluded_app(" COM.EXAMPLE.VAULT ", &s));
        assert!(is_excluded_app("C:\\Program Files\\keepass.exe", &s));
        assert!(is_excluded_app("keepass", &s));
        assert!(!is_excluded_app("com.apple.Safari", &s));
        assert!(!is_excluded_app("", &s));
    }

    fn settings() -> Settings {
        Settings::default()
    }

    fn ctx<'a>(app: Option<&'a str>, formats: &'a [&'a str]) -> CaptureContext<'a> {
        CaptureContext {
            source_app_id: app,
            format_names: formats,
            written_by_self: false,
        }
    }

    #[test]
    fn ordinary_change_is_captured() {
        assert!(should_capture(
            &ctx(Some("com.apple.Safari"), &["public.utf8-plain-text"]),
            &settings()
        ));
        assert!(should_capture(&ctx(None, &[]), &settings()));
    }

    #[test]
    fn paused_capture_is_ignored() {
        let mut s = settings();
        s.capture_paused = true;
        assert!(!should_capture(&ctx(Some("com.apple.Safari"), &[]), &s));
    }

    #[test]
    fn own_writes_are_ignored() {
        let c = CaptureContext {
            written_by_self: true,
            ..ctx(None, &[])
        };
        assert!(!should_capture(&c, &settings()));
    }

    #[test]
    fn excluded_apps_are_ignored_case_insensitively() {
        let mut s = settings();
        s.excluded_app_ids = vec!["com.example.Vault".into(), "Secret.exe".into()];
        assert!(!should_capture(&ctx(Some("com.example.Vault"), &[]), &s));
        assert!(!should_capture(&ctx(Some("COM.EXAMPLE.VAULT"), &[]), &s));
        assert!(!should_capture(&ctx(Some("secret.EXE"), &[]), &s));
        // Executable name with or without extension, or as a full path.
        assert!(!should_capture(&ctx(Some("secret"), &[]), &s));
        assert!(!should_capture(
            &ctx(Some("C:\\Program Files\\Secret\\Secret.exe"), &[]),
            &s
        ));
        assert!(!should_capture(&ctx(Some(" com.example.Vault "), &[]), &s));
        assert!(should_capture(&ctx(Some("com.example.Notes"), &[]), &s));
    }

    #[test]
    fn concealed_transient_and_generated_markers_are_ignored() {
        for marker in [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
            "com.agilebits.onepassword",
            "de.petermaurer.TransientPasteboardType",
            "com.typeit4me.clipping",
            "Pasteboard generator type",
            "ExcludeClipboardContentFromMonitorProcessing",
            "CanIncludeInClipboardHistory",
            "Clipboard Viewer Ignore",
            "x-kde-passwordManagerHint",
            "ORG.NSPASTEBOARD.CONCEALEDTYPE",
        ] {
            let formats = ["public.utf8-plain-text", marker];
            assert!(
                !should_capture(&ctx(Some("com.apple.Safari"), &formats), &settings()),
                "{marker}"
            );
        }
    }

    #[test]
    fn source_marker_alone_is_not_a_privacy_marker() {
        // nspasteboard.org's source type names the origin app; it is not a
        // request to skip the change.
        let formats = ["org.nspasteboard.source", "public.utf8-plain-text"];
        assert!(should_capture(&ctx(None, &formats), &settings()));
    }

    #[test]
    fn default_exclusions_cover_major_password_managers_on_every_platform() {
        let ids = default_excluded_app_ids();
        let s = settings();
        for app in [
            // macOS
            "com.1password.1password",
            "com.agilebits.onepassword7",
            "com.bitwarden.desktop",
            "org.keepassxc.keepassxc",
            "com.apple.keychainaccess",
            "com.apple.Passwords",
            "com.lastpass.LastPass",
            "com.dashlane.Dashlane",
            // Windows
            "1Password.exe",
            "KeePass.exe",
            "KeePassXC.exe",
            "Bitwarden.exe",
            "CredentialUIBroker.exe",
            // Linux
            "keepassxc",
            "org.keepassxc.KeePassXC",
            "seahorse",
            "org.gnome.seahorse.Application",
            "kwalletmanager5",
            "1password",
        ] {
            assert!(
                !should_capture(&ctx(Some(app), &[]), &s),
                "{app} should be excluded"
            );
        }
        let mut sorted = ids.clone();
        sorted.sort();
        sorted.dedup();
        assert_eq!(sorted.len(), ids.len(), "no duplicates");
    }

    #[test]
    fn settings_default_uses_the_default_exclusions() {
        assert_eq!(
            Settings::default().excluded_app_ids,
            default_excluded_app_ids()
        );
    }
}
