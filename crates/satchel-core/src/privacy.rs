//! Rules that decide whether a clipboard change may be stored at all.
//! Security-critical: when in doubt, do not capture.

use crate::model::Settings;

/// Facts about a clipboard change gathered by the platform watcher before any
/// content is read.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct CaptureContext<'a> {
    /// Bundle id / executable of the app that owned the clipboard, if known.
    pub source_app_id: Option<&'a str>,
    /// Raw pasteboard type / clipboard format names present on the change,
    /// e.g. `org.nspasteboard.ConcealedType` or
    /// `ExcludeClipboardContentFromMonitorProcessing`.
    pub format_names: &'a [&'a str],
    /// True when Satchel itself wrote this change (our own paste/copy).
    pub written_by_self: bool,
}

/// Returns false when the change must be ignored: capture paused, written by
/// ourselves, source app excluded, or the change is marked concealed,
/// transient or auto-generated by its owner (nspasteboard.org conventions and
/// the Windows clipboard-history opt-out formats).
///
/// Fails closed: app ids match case-insensitively, by file name when a path is
/// given, and with or without a trailing `.exe`; marker formats match
/// case-insensitively. A Windows `CanIncludeInClipboardHistory` format counts
/// as an opt-out whenever it is present, since its value is not visible here.
pub fn should_capture(ctx: &CaptureContext<'_>, settings: &Settings) -> bool {
    if settings.capture_paused || ctx.written_by_self {
        return false;
    }
    if ctx.format_names.iter().any(|f| is_privacy_marker(f)) {
        return false;
    }
    match ctx.source_app_id.map(normalize_app_id) {
        Some(app) if !app.is_empty() => !settings
            .excluded_app_ids
            .iter()
            .any(|ex| normalize_app_id(ex) == app),
        _ => true,
    }
}

/// True when `app_id` is on the excluded-apps list, matched as
/// `should_capture` matches it. Used again before a link preview is fetched,
/// since the list may have changed since the clip was captured.
pub fn is_excluded_app(app_id: &str, settings: &Settings) -> bool {
    let app = normalize_app_id(app_id);
    !app.is_empty() && settings.excluded_app_ids.iter().any(|ex| normalize_app_id(ex) == app)
}

/// Pasteboard types / clipboard formats whose presence means "do not record".
const PRIVACY_MARKERS: &[&str] = &[
    // nspasteboard.org conventions (macOS).
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    // Older vendor markers still written by some apps.
    "com.agilebits.onepassword",
    "de.petermaurer.TransientPasteboardType",
    "com.typeit4me.clipping",
    "Pasteboard generator type",
    // Windows clipboard history / monitor opt-outs.
    "ExcludeClipboardContentFromMonitorProcessing",
    "CanIncludeInClipboardHistory",
    "Clipboard Viewer Ignore",
    // KDE / KeePassXC on Linux.
    "x-kde-passwordManagerHint",
    "application/x-kde-passwordManagerHint",
];

fn is_privacy_marker(format: &str) -> bool {
    let f = format.trim();
    PRIVACY_MARKERS.iter().any(|m| m.eq_ignore_ascii_case(f))
}

/// Lowercased file name of an app id, without a trailing `.exe`.
fn normalize_app_id(id: &str) -> String {
    let id = id.trim();
    let base = id.rsplit(['/', '\\']).next().unwrap_or(id);
    let lower = base.to_lowercase();
    match lower.strip_suffix(".exe") {
        Some(stem) => stem.to_string(),
        None => lower,
    }
}

/// App ids excluded out of the box: common password managers and keychains on
/// macOS, Windows and Linux.
pub fn default_excluded_app_ids() -> Vec<String> {
    DEFAULT_EXCLUDED_APP_IDS
        .iter()
        .map(|s| (*s).to_string())
        .collect()
}

